<script>
(function(){
  const CLIENT_CODE = "CLTTEST001";
  const TOKEN_ENDPOINT = "https://royalxpay.com/proxy/token"; // must be HTTPS

  let accessToken = null;
  let ws = null;
  let aiBubbleEl = null;
  let aiBuffer = "";
  let wsConnected = false;
  let pendingSendQueue = [];
  let messageCompleted = false; // 🆕 Flag to detect end of stream
  let finalizeTimeout; // 🆕 timeout handler

  // Append bubble to chat
  function appendChatBubbleAI(text, side="left") {
    const chatArea = document.getElementById('chatMessagesAI');
    const bubble = document.createElement('div');
    bubble.textContent = text;
    bubble.style.maxWidth = '80%';
    bubble.style.padding = '8px 12px';
    bubble.style.borderRadius = '16px';
    bubble.style.lineHeight = '1.4';
    bubble.style.wordWrap = 'break-word';
    bubble.style.background = side === "left" ? "#e5e5ea" : "#007aff";
    bubble.style.color = side === "left" ? "#000" : "#fff";
    bubble.style.alignSelf = side === "left" ? "flex-start" : "flex-end";
    chatArea.appendChild(bubble);
    chatArea.scrollTop = chatArea.scrollHeight;
  }

  async function fetchAccessTokenAI() {
    try {
      const res = await axios.post(TOKEN_ENDPOINT, { client_code: CLIENT_CODE }, {
        headers: { 'Content-Type': 'application/json' }
      });
      accessToken = res.data.access_token || res.data.token;
      if (!accessToken) throw new Error("No access_token in response");
      return accessToken;
    } catch (err) {
      appendChatBubbleAI("❌ Failed to get access token.", "left");
      throw err;
    }
  }

  function buildWsUrlAI(token, useSecure = true) {
    const proto = useSecure ? "wss" : "ws";
    return `${proto}://interactivebyskiphi.skiphi.com/ws/ai-chat/?token=${encodeURIComponent(token)}&clientCode=${encodeURIComponent(CLIENT_CODE)}`;
  }

  async function ensureTokenAndSocketAI() {
    if (!accessToken) await fetchAccessTokenAI();
    if (wsConnected && ws && ws.readyState === WebSocket.OPEN) return;
    return connectWebSocketAI(accessToken);
  }

  function connectWebSocketAI(token) {
    return new Promise((resolve, reject) => {
      const url = buildWsUrlAI(token, true); // ✅ always wss
      const socket = new WebSocket(url);

      socket.onopen = () => {
        ws = socket;
        window.chatSocket = socket;
        wsConnected = true;

        while (pendingSendQueue.length) {
          try { ws.send(JSON.stringify(pendingSendQueue.shift())); } catch(e){}
        }
        appendChatBubbleAI("🔗 Connected to AI assistant.", "left");
        resolve();
      };

      socket.onmessage = (ev) => {
        console.log("WS DATA:", ev.data);
        let parsed;
        try { parsed = JSON.parse(ev.data); } catch (e) { return; }

        // Skip phone prompt
        if (parsed.message && parsed.message.includes("valid 10-digit number")) return;

        if (parsed.status && parsed.status.includes("completed")) {
          messageCompleted = true;
          finalizeAIBubble();
          return;
        }

        if (messageCompleted) {
          console.log("🔁 Skipping repeated full message:", parsed.message);
          return;
        }

        if (parsed.message) {
  // If we've already built the same message, skip it
  if (parsed.message === aiBuffer) {
    console.log("⚠️ Duplicate full message detected, skipping.");
    return;
  }

  if (!aiBubbleEl) {
    aiBuffer = "";
    aiBubbleEl = createAIBubble();
  }

  if (parsed.message === aiBuffer) {
  // Final full message duplicate, skip it
  console.log("🛑 Duplicate final message skipped:", parsed.message);
  return;
}

aiBuffer += parsed.message;
  updateAIBubble(aiBuffer);
  resetFinalizeTimeout();
}

      };

      socket.onerror = () => {
        wsConnected = false;
        appendChatBubbleAI("❌ Chat connection failed.", "left");
        reject(new Error("WebSocket error"));
      };

      socket.onclose = () => {
        wsConnected = false;
        aiBubbleEl = null;
        aiBuffer = "";
        messageCompleted = false;
        clearTimeout(finalizeTimeout);
      };
    });
  }

  function sendMessageToAI(messageText) {
    const msg = {
      text: messageText,
      sender: "user",
      time: new Date().toISOString(),
      id: Date.now().toString(),
      status: "delivered"
    };

    console.log("Sending to AI:", JSON.stringify(msg));

    messageCompleted = false; // 🆕 Reset flag before each send
    resetFinalizeTimeout();   // 🆕 start response timer

    if (ws && ws.readyState === WebSocket.OPEN) {
      aiBubbleEl = createAIBubble();
      aiBuffer = "";
      ws.send(JSON.stringify(msg));
    } else {
      pendingSendQueue.push(msg);
      ensureTokenAndSocketAI().catch(() => appendChatBubbleAI("❌ Chat unavailable.", "left"));
      aiBubbleEl = createAIBubble();
      aiBuffer = "";
    }
  }

  function createAIBubble() {
    const chatArea = document.getElementById('chatMessagesAI');
    const bubble = document.createElement('div');
    bubble.textContent = "💬 ...";
    bubble.style.maxWidth = '80%';
    bubble.style.padding = '8px 12px';
    bubble.style.borderRadius = '16px';
    bubble.style.lineHeight = '1.4';
    bubble.style.background = "#e5e5ea";
    bubble.style.color = "#000";
    bubble.style.alignSelf = "flex-start";
    chatArea.appendChild(bubble);
    chatArea.scrollTop = chatArea.scrollHeight;
    return bubble;
  }

  function updateAIBubble(text) {
    if (aiBubbleEl) aiBubbleEl.textContent = text;
    document.getElementById('chatMessagesAI').scrollTop = document.getElementById('chatMessagesAI').scrollHeight;
  }

  function finalizeAIBubble() {
    if (aiBubbleEl) aiBubbleEl.textContent = aiBuffer || "🤖 (no reply)";
    aiBubbleEl = null; 
    aiBuffer = "";
    clearTimeout(finalizeTimeout);
  }

  // 🆕 Timeout function
  function resetFinalizeTimeout() {
    clearTimeout(finalizeTimeout);
    finalizeTimeout = setTimeout(() => {
      if (!messageCompleted) {
        console.log("⏰ No response received, finalizing bubble.");
        finalizeAIBubble();
        appendChatBubbleAI("⚠️ No response from server, please try again.", "left");
      }
    }, 7000); // wait max 7s
  }

  // Global helpers
  window.openChatBoxAI = function() {
    document.getElementById('chatBoxAI').style.display = 'block';
    const chatArea = document.getElementById('chatMessagesAI');
    chatArea.innerHTML = '';
    appendChatBubbleAI("👋 Hi there! I am your assistant.", "left");
    appendChatBubbleAI("How can I help you today?", "left");
    ensureTokenAndSocketAI().catch(() => {
      appendChatBubbleAI("❌ Unable to connect. Please try later.", "left");
    });
  };

  window.closeChatBoxAI = function() {
    document.getElementById('chatBoxAI').style.display = 'none';
  };

  window.chatHandleKeyAI = function(e) {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      const input = document.getElementById('chatInputBoxAI');
      const text = input.value.trim();
      if (text) {
        appendChatBubbleAI("🧑 " + text, "right");
        sendMessageToAI(text);
        input.value = "";
      }
    }
  };
})();
</script>
